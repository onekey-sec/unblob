"""Generate the PackageForTheWeb integration test fixtures.

There is no redistributable InstallShield single-file installer to borrow, so
the inputs are written by this script following the layout as ISx
(https://github.com/lifenjoiner/ISx) reads it: a 46-byte header, then one
0x138-byte attribute record (or a compact record plus UTF-16 name for the
"ISSetupStream" layout) per member, then the member data.

Member data may be obfuscated: every byte is nibble-swapped and XORed with a
key derived from the file name, and unicode launcher members are
zlib-deflated on top of that.

The encoder below was verified against ISx itself: its gen_key/decode_byte/
encode_byte/decode_data/decode_data_ustrm functions, compiled verbatim from
ISx.c, decode every generated member to the expected content and re-encode it
to byte-identical blobs, so the fixtures exercise the real on-disk format
rather than just the handler's own assumptions.

Run from the repository root:

    uv run python tests/integration/archive/installshield_pftw/gen_pftw.py
"""

import struct
import zlib
from pathlib import Path

OUTPUT = Path(__file__).parent / "__input__"

HEADER_SIZE = 0x2E
FILE_ATTRIBUTES_SIZE = 0x138
STREAM_FILE_ATTRIBUTES_SIZE = 0x18
NAME_SIZE = 260  # MAX_PATH

SIG_PFTW = b"InstallShield\x00"
SIG_STREAM = b"ISSetupStream\x00"

KEY_MAGIC = (0x13, 0x35, 0x86, 0x07)
_NIBBLE_SWAP = bytes((i << 4 | i >> 4) & 0xFF for i in range(256))

ENCODED_BLOCK_LEN = 1024


def _gen_mask(seed: bytes) -> bytes:
    """~key of the obfuscation stream: ~(seed ^ KEY_MAGIC)."""
    return bytes(
        ~(b ^ KEY_MAGIC[i % len(KEY_MAGIC)]) & 0xFF for i, b in enumerate(seed)
    )


def encode(data: bytes, seed: bytes, block_size: int) -> bytes:
    """Obfuscate member data, the exact inverse of the decode pass."""
    key = _gen_mask(seed)
    mask = (key * (block_size // len(key) + 1))[:block_size]
    parts = []
    for start in range(0, len(data), block_size):
        block = data[start : start + block_size]
        parts.append(
            (int.from_bytes(block) ^ int.from_bytes(mask[: len(block)]))
            .to_bytes(len(block))
            .translate(_NIBBLE_SWAP)
        )
    return b"".join(parts)


def encode_member(
    data: bytes, seed: bytes, encoded_flags: int, is_stream: bool
) -> bytes:
    if encoded_flags & 0x4:
        return encode(data, seed, ENCODED_BLOCK_LEN)
    if encoded_flags & 0x2 and not is_stream:
        return encode(data, seed, len(data))
    return data


def header(magic: bytes, num_files: int, type_: int = 0) -> bytes:
    return struct.pack(
        "<14sHI8sH16s", magic, num_files, type_, b"\x00" * 8, 0, b"\x00" * 16
    )


def file_attributes(
    name: bytes, encoded_flags: int, file_len: int, inflate: int
) -> bytes:
    return struct.pack(
        "<260sII I 8s H 30s",
        name,
        encoded_flags,
        0,
        file_len,
        b"\x00" * 8,
        inflate,
        b"\x00" * 30,
    )


def stream_file_attributes(
    filename_len: int, encoded_flags: int, file_len: int, inflate: int
) -> bytes:
    return struct.pack(
        "<II2sI8sH",
        filename_len,
        encoded_flags,
        b"\x00" * 2,
        file_len,
        b"\x00" * 8,
        inflate,
    )


def classic_member(
    name: bytes, content: bytes, encoded_flags: int, inflate: int
) -> bytes:
    data = zlib.compress(content) if inflate else content
    data = encode_member(data, name, encoded_flags, is_stream=False)
    return file_attributes(name, encoded_flags, len(data), inflate) + data


def stream_member(
    name: str, content: bytes, encoded_flags: int, inflate: int, type_: int
) -> bytes:
    seed = name.encode("utf-8")
    data = zlib.compress(content) if inflate else content
    data = encode_member(data, seed, encoded_flags, is_stream=True)
    name_bytes = name.encode("utf-16-le")
    attrs = stream_file_attributes(len(name_bytes), encoded_flags, len(data), inflate)
    if type_ == 4:
        attrs += b"\x00" * STREAM_FILE_ATTRIBUTES_SIZE
    return attrs + name_bytes + data


def classic_package(members: list[bytes]) -> bytes:
    return header(SIG_PFTW, len(members)) + b"".join(members)


def stream_package(members: list[bytes], type_: int) -> bytes:
    return header(SIG_STREAM, len(members), type_) + b"".join(members)


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)

    readme = b"This package was generated by gen_pftw.py for the unblob test suite.\r\n"

    # classic "InstallShield" layout: every decode mode
    classic = classic_package(
        [
            # stored plain, no obfuscation, no deflate
            classic_member(b"plain.txt", b"plain stored file\r\n", 0, 0),
            # flag 0x2: whole-file keyed obfuscation ("Mfile"), deflated
            classic_member(b"mfile.ini", readme * 40, 0x2, 1),
            # flag 0x4: 1024-byte keyed blocks ("M1024"), deflated
            classic_member(b"m1024.ini", readme * 40, 0x4, 1),
            # flag 0x6: M1024 obfuscation, deflated (as InstallShield writes it)
            classic_member(b"m1024_6.ini", readme * 40, 0x6, 1),
            # flag 0x2: Mfile obfuscation, stored
            classic_member(b"mfile_stored.bin", bytes(range(256)) * 3, 0x2, 0),
            # obfuscated but not deflated
            classic_member(b"encoded_only.ini", readme * 10, 0x6, 0),
            # a member in a subdirectory
            classic_member(b"lang\\0x0409.ini", readme, 0x6, 1),
            # an empty member
            classic_member(b"empty.bin", b"", 0x6, 1),
        ]
    )
    (OUTPUT / "classic.pftw").write_bytes(classic)
    (OUTPUT / "classic.pftw.padded").write_bytes(b"\x00" * 16 + classic + b"\x00" * 16)

    # "ISSetupStream" layout, type 4: compact records, UTF-16 names
    stream = stream_package(
        [
            stream_member("unicode 0x0409.ini", readme * 20, 0x4, 1, 4),
            stream_member("setup.msi", b"fake msi" * 100, 0x4, 1, 4),
            stream_member("plain.bin", b"plain", 0, 0, 4),
        ],
        type_=4,
    )
    (OUTPUT / "stream.pftw").write_bytes(stream)

    # type 2 stream package: no extra attribute padding
    stream2 = stream_package(
        [stream_member("app.exe", b"MZ" + b"\x00" * 30, 0x4, 1, 2)],
        type_=2,
    )
    (OUTPUT / "stream2.pftw").write_bytes(stream2)


if __name__ == "__main__":
    main()
