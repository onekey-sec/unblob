def build_inode(size: int, data: bytes) -> File:
    header = (
        struct.pack(">I", FSType.FILE)
        + struct.pack(">I", 0)
        + struct.pack(">I", size)
        + struct.pack(">I", 0)
    )
    filename = b"file" + b"\x00" * 12
    return File.from_bytes(header + filename + data)


